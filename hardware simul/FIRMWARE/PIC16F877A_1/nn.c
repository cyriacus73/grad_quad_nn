int16_t sigmoid(int16_t z)
{
    if (z <= -1024) return 0;
    if (z >= 1024) return 256;
    uint8_t idx = (uint8_t)((z + 1024) >> 3);
    return sigmoid_lut_256[idx];
}

int16_t sigmoid_deriv(int16_t h)
{
    return QMUL(h, 256 - h);
}

int16_t nn_forward(int16_t x, int16_t h[NN_HIDDEN])
{
    int32_t acc = b2;
    for (uint8_t i = 0; i < NN_HIDDEN; i++) {
        int32_t z = QMUL(w1[i], x) + b1[i];
        h[i] = sigmoid((int16_t)z);
        acc += QMUL(w2[i], h[i]);
    }
    return (int16_t)acc;
}
